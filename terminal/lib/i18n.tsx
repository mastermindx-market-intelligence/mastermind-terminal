// Non-hook LEX lookup for imperative contexts (e.g. chart legend meta assembled outside React render).
// Reads the live <html data-lang> attribute; callers refresh on their own rebuild paths, so a language
// toggle updates these strings on the next legend rebuild rather than instantly (acceptable for notes).
export function tPlain(key: string, fallback?: string): string {
  const e = LEX[key];
  if (!e) return fallback ?? key;
  const zh = typeof document !== "undefined" && document.documentElement.getAttribute("data-lang") === "zh";
  return zh ? e[1] : e[0];
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

/**
 * Switch the UI language from imperative code (the account-prefs store applies the language saved
 * on the Supabase account this way, on the same load that reads market prefs).
 *
 * Every mounted LangProvider re-reads the attribute on `mm:lang`, so this is not a second source
 * of truth — it is the same three writes setLang makes, minus the local setState that the event
 * already covers.
 */
export function applyLang(l: Lang) {
  try { localStorage.setItem("mm.lang", l); } catch { /* storage blocked */ }
  if (typeof document === "undefined") return;
  document.documentElement.setAttribute("data-lang", l);
  window.dispatchEvent(new CustomEvent("mm:lang"));
}

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const read = () => { const v = document.documentElement.getAttribute("data-lang"); if (v === "zh" || v === "en") setLangState(v); };
    read();
    window.addEventListener("mm:lang", read);
    return () => window.removeEventListener("mm:lang", read);
  }, []);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    applyLang(l);
  }, []);
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);

export function useT() {
  const { lang } = useContext(Ctx);
  return useCallback((key: string, fallback?: string) => {
    const e = LEX[key];
    return e ? (lang === "zh" ? e[1] : e[0]) : (fallback ?? key);
  }, [lang]);
}
