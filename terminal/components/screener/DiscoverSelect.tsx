"use client";

import { Children, Fragment, isValidElement, useEffect, useId, useLayoutEffect, useRef, useState, type ReactNode, type SelectHTMLAttributes } from "react";
import { createPortal } from "react-dom";
import styles from "./DiscoverWorkspace.module.css";

type Option = { value: string; label: ReactNode; text: string; disabled: boolean };
type Props = Omit<SelectHTMLAttributes<HTMLSelectElement>, "onChange" | "multiple" | "size"> & {
  onChange?: (event: { target: { value: string } }) => void;
};
const words = (value: ReactNode): string => Children.toArray(value).map(x => isValidElement<{ children?: ReactNode }>(x) ? words(x.props.children) : String(x)).join("");
function optionsFrom(children: ReactNode): Option[] {
  return Children.toArray(children).flatMap(child => {
    if (!isValidElement<{ children?: ReactNode; value?: unknown; disabled?: boolean }>(child)) return [];
    if (child.type === Fragment || child.type === "optgroup") return optionsFrom(child.props.children);
    if (child.type !== "option") return [];
    return [{ value: String(child.props.value ?? words(child.props.children)), label: child.props.children, text: words(child.props.children), disabled: !!child.props.disabled }];
  });
}

/** Designed listbox, using the existing option/value contract. No OS popup. */
export default function DiscoverSelect({ children, value, onChange, disabled, className = "", title, ...rest }: Props) {
  const options = optionsFrom(children), selected = options.find(o => o.value === String(value ?? ""));
  const id = useId(), trigger = useRef<HTMLButtonElement>(null), panel = useRef<HTMLDivElement>(null), searchRef = useRef<HTMLInputElement>(null), listRef = useRef<HTMLDivElement>(null);
  const [open, setOpen] = useState(false), [query, setQuery] = useState(""), [active, setActive] = useState(0);
  const [position, setPosition] = useState({ left: 0, top: 0, width: 240, maxHeight: 320 });
  const label = rest["aria-label"] || title || "Choose";
  const filtered = options.filter(o => o.text.toLocaleLowerCase().includes(query.toLocaleLowerCase()));
  const zh = typeof document !== "undefined" && document.documentElement.dataset.lang === "zh";
  const close = (restore = false) => { setOpen(false); setQuery(""); if (restore) trigger.current?.focus(); };
  const choose = (o: Option) => { if (!o.disabled) { onChange?.({ target: { value: o.value } }); close(true); } };
  useLayoutEffect(() => {
    if (!open) return;
    const place = () => {
      const r = trigger.current?.getBoundingClientRect(); if (!r) return;
      const width = Math.min(Math.max(r.width, 260), window.innerWidth - 24);
      const viewport = window.visualViewport;
      const viewportTop = viewport?.offsetTop ?? 0;
      const below = (viewport?.height ?? window.innerHeight) + viewportTop - r.bottom - 16, above = r.top - viewportTop - 16;
      const height = Math.min(360, Math.max(160, below >= 180 ? below : above));
      setPosition({ left: Math.max(12, Math.min(r.left, window.innerWidth - width - 12)), top: below >= 180 ? r.bottom + 6 : Math.max(12, r.top - height - 6), width, maxHeight: height });
    };
    place(); window.visualViewport?.addEventListener("resize", place); window.addEventListener("resize", place); window.addEventListener("scroll", place, true);
    return () => { window.visualViewport?.removeEventListener("resize", place); window.removeEventListener("resize", place); window.removeEventListener("scroll", place, true); };
  }, [open]);
  useEffect(() => {
    if (!open) return;
    const frame = requestAnimationFrame(() => (options.length > 8 ? searchRef.current : listRef.current)?.focus());
    const outside = (e: PointerEvent) => { const target = e.target as Node; if (!panel.current?.contains(target) && !trigger.current?.contains(target)) close(); };
    document.addEventListener("pointerdown", outside);
    return () => { cancelAnimationFrame(frame); document.removeEventListener("pointerdown", outside); };
    // Options can be regenerated by the parent without stealing listbox focus.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open]);
  useEffect(() => { if (open) panel.current?.querySelector(`[data-option-index="${active}"]`)?.scrollIntoView({ block: "nearest" }); }, [active, open]);
  const data = Object.fromEntries(Object.entries(rest).filter(([k]) => k.startsWith("data-") || k.startsWith("aria-") || ["id", "style"].includes(k)));
  return <>
    <button {...data} ref={trigger} data-value={String(value ?? "")} type="button" className={`${className} ${styles.select}`} disabled={disabled}
      title={title} role="combobox" aria-label={label} aria-expanded={open} aria-haspopup="listbox" aria-controls={open ? id : undefined}
      onClick={() => { if (open) close(); else { setActive(Math.max(0, options.findIndex(o => o.value === String(value)))); setOpen(true); } }}
      onKeyDown={e => { if (["ArrowDown", "ArrowUp", "Home", "End"].includes(e.key)) { e.preventDefault(); setActive(e.key === "End" || e.key === "ArrowUp" ? options.length - 1 : 0); setOpen(true); } }}>
      <span>{selected?.label ?? label}</span><svg aria-hidden="true" viewBox="0 0 16 16"><path d="m4 6 4 4 4-4" /></svg>
    </button>
    {open && createPortal(<div ref={panel} className={styles.selectPopover} style={position} tabIndex={-1}
      onKeyDown={e => {
        if (e.key === "Escape") { e.preventDefault(); e.stopPropagation(); close(true); }
        if (e.key === "Tab") close(true);
        if (["ArrowDown", "ArrowUp", "Home", "End"].includes(e.key) && !(e.target === searchRef.current && ["Home", "End"].includes(e.key))) {
          e.preventDefault();
          let next = e.key === "Home" ? 0 : e.key === "End" ? filtered.length - 1 : (active + (e.key === "ArrowDown" ? 1 : -1) + filtered.length) % Math.max(1, filtered.length);
          for (let i = 0; i < filtered.length && filtered[next]?.disabled; i++) next = (next + (e.key === "ArrowUp" ? -1 : 1) + filtered.length) % filtered.length;
          setActive(next);
        }
        if (e.key === "Enter" && filtered[active]) { e.preventDefault(); choose(filtered[active]); }
        if (e.key.length === 1 && options.length <= 8) { const i = filtered.findIndex(o => !o.disabled && o.text.toLowerCase().startsWith(e.key.toLowerCase())); if (i >= 0) setActive(i); }
      }}>
      <div className={styles.menuEyebrow}>{label}</div>
      {options.length > 8 && <input ref={searchRef} role="combobox" aria-autocomplete="list" aria-expanded={true} aria-controls={id} aria-activedescendant={filtered[active] ? `${id}-${active}` : undefined} type="search" value={query} aria-label={zh ? `搜索${label}` : `Search ${label}`} placeholder={zh ? "搜索选项…" : "Search options…"} onChange={e => { setQuery(e.target.value); setActive(0); }} className={styles.menuSearch} />}
      <div ref={listRef} tabIndex={-1} id={id} role="listbox" aria-label={label} aria-activedescendant={filtered[active] ? `${id}-${active}` : undefined} className={styles.optionList}>
        {filtered.map((o, i) => <button key={o.value} id={`${id}-${i}`} type="button" role="option" tabIndex={-1} data-option-index={i} data-value={o.value}
          aria-selected={o.value === String(value)} disabled={o.disabled} data-active={i === active || undefined}
          className={styles.option} onPointerMove={() => setActive(i)} onClick={() => choose(o)}>
          <span>{o.label}</span><span aria-hidden="true">{o.value === String(value) ? "✓" : ""}</span>
        </button>)}
        {!filtered.length && <div className={styles.menuEmpty}>{zh ? "没有匹配选项" : "No matching options"}</div>}
      </div>
    </div>, trigger.current?.closest("dialog") ?? document.body)}
  </>;
}
