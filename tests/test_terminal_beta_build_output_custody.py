"""Private generated-output custody regressions for the beta release owner.

The build shim explicitly assigns Turbopack's observed 0664 mode. Every service,
Git, network and build effect remains confined by the existing transaction
fixture; passing these tests does not claim installed or public beta acceptance.
"""
import os
import shlex
import stat
import sys
from types import SimpleNamespace

import pytest

from test_terminal_beta_transaction import A, B, Fixture


pytestmark = pytest.mark.skipif(
    sys.platform != "linux",
    reason="Beta generated-output custody requires the Linux deployment metadata contract",
)


def metadata(path):
    info = path.stat()
    return (path.read_bytes(), info.st_dev, info.st_ino, info.st_uid, info.st_gid,
            stat.S_IMODE(info.st_mode), info.st_size, info.st_mtime_ns, info.st_nlink)


def generated_build(box):
    shim = box.root / "bin/npm"
    anchor = "  (d/'fixture-build-sha').write_text(os.environ['GIT_SHA']+'\\n')"
    extra = r"""
  generated=d/'server/app/page.js'
  generated.parent.mkdir(parents=True,exist_ok=True)
  generated.write_bytes(b'generated application bytes\n')
  generated.chmod(0o664)
  trace=d/'next-minimal-server.js.nft.json'
  trace.write_bytes(b'{"version":1,"files":["server/app/page.js"]}\n')
  trace.chmod(0o664)
  (R/'generated-stage-path').write_text(str(d))
"""
    text = shim.read_text()
    assert text.count(anchor) == 1
    shim.write_text(text.replace(anchor, anchor + extra))


def private_output(box):
    box.target.mkdir(parents=True, exist_ok=True)
    stage = box.target / ".stage.fixture"
    stage.mkdir(mode=0o700)
    app = stage / "terminal"
    app.mkdir(mode=0o700)
    output = app / ".next"
    output.mkdir(mode=0o755)
    valid = output / "aaa.js"
    valid.write_bytes(b"generated bytes\n")
    valid.chmod(0o664)
    return stage, output, valid


def prepare(box, stage, *, expected=None, check=True):
    info = stage.stat()
    identity = expected or f"{info.st_dev}:{info.st_ino}"
    return box.lib(
        f"STAGE_ROOT={shlex.quote(str(stage))}\n"
        f"BETA_BUILD_STAGE_ID={shlex.quote(identity)}\n"
        "beta_prepare_build_output\n", check=check)


def embedded(box, stage, monkeypatch):
    source = box.owner.read_text().split("<<'PY_BUILD_OUTPUT'\n", 1)[1].split(
        "\nPY_BUILD_OUTPUT", 1)[0]
    info = stage.stat()
    monkeypatch.setattr(sys, "argv", [
        "prepare", str(stage), str(box.target), f"{info.st_dev}:{info.st_ino}"])
    exec(compile(source, str(box.owner) + ":PY_BUILD_OUTPUT", "exec"), {})


@pytest.mark.parametrize("resume", [False, True])
def test_generated_0664_output_completes_original_bootstrap_and_resume(tmp_path, resume):
    box = Fixture(tmp_path)
    generated_build(box)
    provenance = None
    prior_bytes = None
    if resume:
        box.flag("fail_build")
        failed = box.run(A, True)
        assert failed.returncode != 0
        provenance = (box.target / ".source-provisioned").resolve()
        prior_bytes = provenance.read_bytes()
        (box.root / "fail_build").unlink()
    result = box.run(A, True)
    assert result.returncode == 0, result.stdout + result.stderr
    assert "beta build output prepared:" in result.stdout
    assert "converted=2" in result.stdout
    assert box.accepted()["accepted_sha"] == A
    assert box.read("active") == "active" and box.read("enabled") == "enabled"
    assert not (box.target / ".release-pending").exists()
    assert not list(box.target.glob(".stage.*"))
    for name in ("next-minimal-server.js.nft.json", "server/app/page.js"):
        assert stat.S_IMODE((box.app / ".next" / name).stat().st_mode) == 0o644
    if provenance:
        assert (box.target / ".source-provisioned").resolve() == provenance
        assert provenance.read_bytes() == prior_bytes
        assert "deps unchanged" in result.stdout


def test_exact_private_conversion_preserves_bytes_inode_owner_mtime_and_cache(tmp_path):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    nested = output / "server"
    nested.mkdir(mode=0o755)
    another = nested / "chunk.js"
    another.write_bytes(b"nested generated bytes\n")
    another.chmod(0o664)
    executable = output / "native-helper"
    executable.write_bytes(b"#!/bin/sh\nexit 0\n")
    executable.chmod(0o755)
    safe = output / "BUILD_ID"
    safe.write_bytes(b"build-fixture\n")
    safe.chmod(0o600)
    cache = output / "cache"
    cache.mkdir(mode=0o700)
    cached = cache / "build-cache"
    cached.write_bytes(b"cache stays with the cache owner\n")
    cached.chmod(0o664)
    watched = [valid, another, executable, safe, cached]
    before = {path: metadata(path) for path in watched}
    result = prepare(box, stage)
    assert "converted=2" in result.stdout
    for path in watched:
        expected = list(before[path])
        if path in (valid, another):
            expected[5] = 0o644
        assert metadata(path) == tuple(expected)
    assert "converted=0" in prepare(box, stage).stdout
    assert metadata(cached) == before[cached]


@pytest.mark.parametrize("defect", [
    "symlink", "directory_symlink", "external_hardlink", "internal_hardlink",
    "fifo", "other_write", "different_group_write", "writable_directory",
    "setid", "secret_name",
])
def test_complete_inventory_refuses_bad_entry_before_any_permission_change(tmp_path, defect):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    outside = box.prod / "immutable-production-source"
    outside.chmod(0o600)
    before_outside = metadata(outside)
    before_valid = metadata(valid)
    bad = output / "zzz-invalid"
    if defect == "symlink":
        bad.symlink_to(outside)
    elif defect == "directory_symlink":
        bad.symlink_to(box.prod, target_is_directory=True)
    elif defect == "external_hardlink":
        os.link(outside, bad)
        before_outside = metadata(outside)
    elif defect == "internal_hardlink":
        os.link(valid, bad)
        before_valid = metadata(valid)
    elif defect == "fifo":
        os.mkfifo(bad, 0o600)
    elif defect == "writable_directory":
        bad.mkdir()
        bad.chmod(0o775)
    else:
        if defect == "secret_name":
            bad = output / ".env.private"
        bad.write_bytes(b"unexpected generated state\n")
        bad.chmod({"other_write": 0o666, "different_group_write": 0o660,
                   "setid": 0o4644, "secret_name": 0o600}[defect])
    result = prepare(box, stage, check=False)
    assert result.returncode != 0
    assert metadata(valid) == before_valid
    assert metadata(outside) == before_outside


@pytest.mark.parametrize("substitute", ["live", "quarantine", "other_stage", "escape"])
def test_only_this_exact_private_stage_is_eligible(tmp_path, substitute):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    original = stage.stat()
    expected = f"{original.st_dev}:{original.st_ino}"
    if substitute in ("live", "quarantine"):
        path = box.target / "terminal" / (".next" if substitute == "live" else ".next.broken")
        path.mkdir(parents=True)
    elif substitute == "other_stage":
        path = box.target / ".stage.other"
        path.mkdir(mode=0o700)
    else:
        path = stage / ".." / stage.name
    before = metadata(valid)
    result = prepare(box, path, expected=expected, check=False)
    assert result.returncode != 0
    assert metadata(valid) == before
    denied = box.lib(
        f"TARGET=production; STAGE_ROOT={shlex.quote(str(stage))}; "
        f"BETA_BUILD_STAGE_ID={expected}; beta_prepare_build_output", check=False)
    assert denied.returncode == 64
    assert metadata(valid) == before


@pytest.mark.parametrize("race", ["replacement", "new_alias", "ancestor"])
def test_changed_identity_or_alias_before_mutation_is_refused(tmp_path, monkeypatch, race):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    outside = box.prod / "immutable-production-source"
    outside.chmod(0o600)
    before = metadata(outside)
    real_open = os.open
    openings = []
    fired = []

    def raced_open(path, flags, *args, **kwargs):
        if path == valid.name:
            openings.append(True)
            if len(openings) == 2:
                fired.append(True)
                if race == "replacement":
                    valid.unlink()
                    valid.symlink_to(outside)
                elif race == "new_alias":
                    os.link(valid, outside.parent / "racing-alias")
                else:
                    output.rename(output.with_name(".next-displaced"))
                    output.symlink_to(box.prod, target_is_directory=True)
        return real_open(path, flags, *args, **kwargs)

    monkeypatch.setattr(os, "open", raced_open)
    with pytest.raises((SystemExit, OSError)):
        embedded(box, stage, monkeypatch)
    assert fired
    assert metadata(outside) == before
    if race == "new_alias":
        assert stat.S_IMODE(valid.stat().st_mode) == 0o664
    elif race == "ancestor":
        displaced = output.with_name(".next-displaced") / valid.name
        assert stat.S_IMODE(displaced.stat().st_mode) == 0o664


def test_same_size_content_change_during_verification_prevents_chmod(tmp_path, monkeypatch):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    inode = valid.stat().st_ino
    original = metadata(valid)
    real_read = os.read
    calls = []
    fired = []

    def raced_read(fd, size):
        if os.fstat(fd).st_ino == inode:
            calls.append(True)
            if len(calls) == 3:
                fired.append(True)
                valid.write_bytes(b"X" * len(original[0]))
                os.utime(valid, ns=(valid.stat().st_atime_ns, original[7]))
        return real_read(fd, size)

    monkeypatch.setattr(os, "read", raced_read)
    with pytest.raises(SystemExit):
        embedded(box, stage, monkeypatch)
    assert fired
    assert stat.S_IMODE(valid.stat().st_mode) == 0o664


def test_xattr_exposure_or_inspection_failure_refuses_before_mutation(tmp_path, monkeypatch):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    before = metadata(valid)
    inode = valid.stat().st_ino
    real_listxattr = os.listxattr

    def exposed(fd, *args, **kwargs):
        if isinstance(fd, int) and os.fstat(fd).st_ino == inode:
            return ["system.posix_acl_access"]
        return real_listxattr(fd, *args, **kwargs)

    monkeypatch.setattr(os, "listxattr", exposed)
    with pytest.raises(SystemExit, match="extended metadata"):
        embedded(box, stage, monkeypatch)
    assert metadata(valid) == before

    def unreadable(fd, *args, **kwargs):
        raise OSError("injected xattr inspection error")

    monkeypatch.setattr(os, "listxattr", unreadable)
    with pytest.raises((SystemExit, OSError)):
        embedded(box, stage, monkeypatch)
    assert metadata(valid) == before



@pytest.mark.parametrize("kind", ["file", "directory"])
@pytest.mark.parametrize("field", ["st_uid", "st_gid"])
def test_foreign_ownership_refuses_before_any_permission_change(tmp_path, monkeypatch, kind, field):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    subject = valid
    if kind == "directory":
        subject = output / "zzz-foreign"
        subject.mkdir(mode=0o755)
    identity = (subject.stat().st_dev, subject.stat().st_ino)
    before = metadata(valid)
    outside = box.prod / "immutable-production-source"
    outside_before = metadata(outside)
    real_stat, real_fstat = os.stat, os.fstat
    inspected = []

    def foreign(info):
        if (info.st_dev, info.st_ino) != identity:
            return info
        values = {name: getattr(info, name) for name in dir(info) if name.startswith("st_")}
        values[field] += 1
        inspected.append(True)
        return SimpleNamespace(**values)

    # Present consistent foreign ownership through both pathname and descriptor
    # APIs. No root/chown privilege is needed, so hosted Linux CI exercises this
    # guard rather than skipping it for a non-root runner.
    with monkeypatch.context() as patch:
        patch.setattr(os, "stat", lambda *args, **kwargs: foreign(real_stat(*args, **kwargs)))
        patch.setattr(os, "fstat", lambda *args, **kwargs: foreign(real_fstat(*args, **kwargs)))
        with pytest.raises(SystemExit, match="custody"):
            embedded(box, stage, patch)
    assert inspected
    assert metadata(valid) == before
    assert metadata(outside) == outside_before


@pytest.mark.parametrize("change", ["membership", "xattr"])
def test_late_generated_state_change_is_refused_before_preparation_completes(tmp_path, monkeypatch, change):
    box = Fixture(tmp_path)
    stage, output, valid = private_output(box)
    inode = valid.stat().st_ino
    outside = box.prod / "immutable-production-source"
    outside_before = metadata(outside)
    real_fchmod, real_listxattr = os.fchmod, os.listxattr
    fired = []

    def change_after_chmod(fd, mode):
        result = real_fchmod(fd, mode)
        if os.fstat(fd).st_ino == inode:
            fired.append(True)
            if change == "membership":
                late = output / "late-valid.js"
                late.write_bytes(b"late generated bytes\n")
                late.chmod(0o644)
        return result

    def late_metadata(fd, *args, **kwargs):
        if change == "xattr" and fired and isinstance(fd, int) and os.fstat(fd).st_ino == inode:
            return ["user.late-custody-test"]
        return real_listxattr(fd, *args, **kwargs)

    monkeypatch.setattr(os, "fchmod", change_after_chmod)
    monkeypatch.setattr(os, "listxattr", late_metadata)
    with pytest.raises(SystemExit):
        embedded(box, stage, monkeypatch)
    assert fired
    # Partial preparation is disposable stage state. A late change must not
    # carry success into activation or affect the external production sentinel.
    assert stat.S_IMODE(valid.stat().st_mode) == 0o644
    assert metadata(outside) == outside_before

@pytest.mark.parametrize("accepted,dirty", [(False, False), (True, False), (True, True)])
def test_preparation_failure_precedes_activation_and_preserves_dirty_state(tmp_path, accepted, dirty):
    box = Fixture(tmp_path)
    generated_build(box)
    prior = None
    if accepted:
        box.bootstrap()
        prior = (box.target / ".runtime-accepted").resolve()
    if dirty:
        lock = box.root / "revisions" / B / "terminal/package-lock.json"
        lock.write_text('{"lockfileVersion":3,"changed":true}\n')
    body = box.owner.read_text()
    needle = "os.fchmod(fd, 0o644)"
    assert body.count(needle) == 1
    box.owner.write_text(body.replace(needle, needle + "; raise SystemExit('injected staged output failure')"))
    start = len(box.effects())
    result = box.run(B if accepted else A, not accepted)
    assert result.returncode != 0
    assert "injected staged output failure" in result.stdout + result.stderr
    assert not list(box.target.glob(".stage.*"))
    later = box.effects()[start:]
    assert not any(line.startswith("service:final-restart:") for line in later)
    if accepted:
        assert (box.target / ".runtime-accepted").resolve() == prior
        assert (box.app / ".next/fixture-build-sha").read_text().strip() == A
        if dirty:
            assert box.pending()["live_inputs_dirty"] is True
            assert box.read("active") == "inactive" and box.read("enabled") == "disabled"
            assert "beta rolled back and verified" not in result.stdout
        else:
            assert not (box.target / ".release-pending").exists()
            assert box.read("active") == "active" and box.read("enabled") == "enabled"
    else:
        assert not (box.target / ".runtime-accepted").exists()
        assert not (box.target / ".release-pending").exists()
        assert not (box.app / ".next").exists()
        assert box.read("active") == "inactive" and box.read("enabled") == "disabled"


@pytest.mark.parametrize("mode", ["0664", "0666"])
def test_final_publisher_still_refuses_write_bits_introduced_after_preparation(tmp_path, mode):
    box = Fixture(tmp_path)
    generated_build(box)
    anchor = 'if [ "$TARGET" = beta ]; then beta_txn_phase activation "$NEW_BUILD_ID" || exit $?; fi'
    body = box.owner.read_text()
    assert body.count(anchor) == 1
    tamper = f'if [ "$TARGET" = beta ]; then chmod {mode} "$STAGE/.next/next-minimal-server.js.nft.json"; fi\n'
    box.owner.write_text(body.replace(anchor, tamper + anchor))
    result = box.run(A, True)
    assert result.returncode != 0
    assert "group/other writable state will not be published over" in result.stdout + result.stderr
    assert not (box.target / ".runtime-accepted").exists()
    assert box.read("active") == "inactive" and box.read("enabled") == "disabled"
