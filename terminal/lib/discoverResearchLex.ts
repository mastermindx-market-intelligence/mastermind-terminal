export type ResearchKey = keyof typeof DISCOVER_RESEARCH_LEX;
export function researchText(key: ResearchKey, lang: string, vars?: Record<string, string | number>) {
  let value: string = DISCOVER_RESEARCH_LEX[key][lang === "zh" ? 1 : 0];
  for (const [key, replacement] of Object.entries(vars ?? {})) value = value.split(`{${key}}`).join(String(replacement));
  return value;
}
export function useResearchT() {
  const { lang } = useLang();
  return useCallback((key: ResearchKey, vars?: Record<string, string | number>) => researchText(key, lang, vars), [lang]);
}
